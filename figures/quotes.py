"""Writes thesis/numbers/quotes_figures.md from the quote constants of the figure
scripts, with corpus provenance, for analysis/qualitative_analysis/check_quotes.py.

    python3 figures/quotes.py && ARM=updated python3 analysis/qualitative_analysis/check_quotes.py --readme thesis/numbers/quotes_figures.md
"""
import glob
import os
import sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(R, "figures"))
import s3_promise as sp, s3_enclosure as se, invitation as inv, cuts, giveway as gw

def run(root, lvl, proto, inst):
    d, = glob.glob(os.path.join(R, root, "*", "*", f"{lvl}_{proto}_6p_grid", inst))
    return d

def prov(model, lvl, proto, inst, ti, spk):
    return f"{model} / 6p / {lvl} / {proto} / {inst} / turn {ti} / Player {spk}"

def by_speaker(d, speaker, frags, after):
    rows = sp.transcript(d)
    n, ti, _ = sp.quote(rows, speaker, frags, after)
    return n, ti

def by_move(d, move):
    rows = sp.transcript(d)
    hit = [(who, ti) for n, k, who, _, ti in rows if k == "msg" and n == move]
    return hit[0]   # the message that rides on the move

out = ["# Verbatim agent quotes shown in the Phase 4 figures (2026-10-11)", "",
       "Generated by `figures/quotes.py` from the quote constants of the figure scripts; every block is "
       "audited by `ARM=updated python3 analysis/qualitative_analysis/check_quotes.py "
       "--readme thesis/numbers/quotes_figures.md`. One `>` line per fragment as drawn "
       "(the figures join fragments of one message with an ellipsis). Provenance "
       "turn = index into `interactions.json` turns, as in `corpus.updated.json`.", ""]

def block(title, items):
    out.append(f"## {title}"); out.append("")
    for move, frags, p in items:
        out.append(f"Move {move}:"); out.append("")
        out.extend("> " + f for f in frags)
        out.append("> — " + p); out.append("")

# fig:s3-10-views
d = run("results_qwen38_grid_updated_prompt_n15_6p", "S3", "hybrid", "instance_00010")
items, after = [], -1
for who, frags in sp.QUOTES:
    n, ti = by_speaker(d, who, frags, after); after = n
    items.append((n, frags, prov("qwen38", "S3", "hybrid", "instance_00010", ti, who)))
block("fig:s3-10-views (figures/s3_promise.py -> s3_worked_views)", items)

# fig:s3-10-enclosure
d = run("results_dsv41_grid_updated_prompt_n15_6p", "S3", "freeform", "instance_00010")
items, after = [], -1
for who, frags in se.QUOTES:
    n, ti = by_speaker(d, who, frags, after); after = n
    items.append((n, frags, prov("dsv41", "S3", "freeform", "instance_00010", ti, who)))
block("fig:s3-10-enclosure (figures/s3_enclosure.py)", items)

# fig:invitation-sealed
items = []
for c in inv.CASES:
    d = run(c["root"], c["level"], c["proto"], c["inst"])
    for move, frags in sorted(c["quotes"].items()):
        who, ti = by_move(d, move)
        items.append((move, frags, prov(c["key"], c["level"], c["proto"], c["inst"], ti, who)))
block("fig:invitation-sealed (figures/invitation.py)", items)

# fig:cut-corridor
items = []
d = run("results_dsv41_grid_updated_prompt_n15_6p", "S3", "freeform", "instance_00014")
for move, frags in cuts.FREEFORM_SAID:
    who, ti = by_move(d, move)
    items.append((move, frags, prov("dsv41", "S3", "freeform", "instance_00014", ti, who)))
d = run("results_dsv41_grid_updated_prompt_n15_6p", "S3", "hybrid", "instance_00014")
for move, frags in gw.SAID:
    who, ti = by_move(d, move)
    items.append((move, frags, prov("dsv41", "S3", "hybrid", "instance_00014", ti, who)))
block("fig:cut-corridor (figures/cuts.py, figures/giveway.py)", items)

open(os.path.join(R, "thesis/numbers/quotes_figures.md"), "w").write("\n".join(out))
print(sum(l.startswith("> —") for l in out), "blocks")
