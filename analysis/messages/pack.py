def ok(x):
    if x is None or (isinstance(x, str) and x.strip() in ("", "nan", "None")):
        return False
    try:
        return not math.isnan(float(x))
    except (TypeError, ValueError):
        return False


def fnum(x, d=1, scale=1.0):
    return f"{float(x) * scale:.{d}f}" if ok(x) else "---"


def pc(x, d=1):
    return fnum(x, d, 100)


def sg(x, d=1, scale=100):
    return f"{float(x) * scale:+.{d}f}" if ok(x) else "---"


def pv(p):
    if not ok(p):
        return "---"
    p = float(p)
    return "<0.0001" if p < 1e-4 else f"{p:.4f}" if p < 1e-3 else f"{p:.3f}"


def th(n):
    return f"{int(round(float(n))):,}" if ok(n) else "---"


def ci(est, lo, hi, scale=100, d=1):
    if not ok(est):
        return "---"
    s = fnum(est, d, scale)
    return f"{s} [{fnum(lo, d, scale)}, {fnum(hi, d, scale)}]" if ok(lo) and ok(hi) else s


def pci(est, lo, hi):
    """Percentage with its interval for the digest, or n/a."""
    return f"{pc(est)} % [{pc(lo)}, {pc(hi)}]" if ok(est) else "n/a"


def T(s):
    """A plain formatted value as LaTeX: thousands with \\, signs and < in math."""
    s = tables.tex_escape(s).replace("\\textless{}", "<")
    s = re.sub(r"(?<=\d),(?=\d{3}(?!\d))", r"\\,", s)
    s = re.sub(r"(^|[\s\[(/])([+-])(?=\d)", lambda m: m.group(1) + "$" + m.group(2) + "$", s)
    return s.replace("<", "$<$")


def E(s):
    return tables.tex_escape(s)


def sc(p):
    return rf"\textsc{{{p}}}"


def plain(s):
    """A LaTeX label back to plain text for the digest."""
    s = re.sub(r"\\(textsc|texttt|emph)\{([^}]*)\}", r"\2", s).replace("\\quad", "").replace("\\,", ",")
    return re.sub(r"[{}$\\]", "", s).replace("_", " ").strip()


def md(s):
    """Plain value for markdown."""
    return str(s).replace("|", "/")


# ---------------------------------------------------------------- the pack

class Pack:
    def __init__(self, scope, src=None, dst=None, calib=None, partial=None):
        self.scope = scope
        self.src = src or os.path.join(OUT, scope)
        self.calib = calib or os.path.join(OUT, "calib")
        self.dst = dst or os.path.join(self.src, "thesis")
        self.made, self.skipped, self.missing = [], [], []
        self.digest = collections.defaultdict(list)
        self.changes = {}  # float name -> label
        self.key = {}  # float name -> headline numbers for changes.md
        self._csv = {}
        self.notes_list = []
        self.handled = set()  # CSV names a dedicated builder rendered (the generic E slots skip them)
        dev = scope != "test"
        self.arm = ("development arm (the updated-prompt arm), S1--S4" if dev
                    else "test arm (the final arm), S2--S4")
        self.status = ("The development arm is the exploratory experiment, so every test here is exploratory."
                       if dev else "Every test here is exploratory.")
        self.arm_md = "development arm (updated-prompt arm, S1-S4), exploratory" if dev else \
            "test arm (final arm, S2-S4), the confirmatory run"
        if partial:  # one model's test arm before the others complete
            names = " and ".join(MNAME.get(m, m) for m in partial)
            self.arm += f", {names} only"
            self.status += (f" Partial run, {names} only: a tier here is {names} alone, and the complete test run "
                            "supersedes every tier-level and pooled number.")
            self.arm_md = f"test arm (final arm, S2-S4), {names} only, a partial run superseded by the complete one"

    # -- inputs
    def csv(self, name, cols=(), where=None):
        key = (where or self.src, name)
        if key not in self._csv:
            p = os.path.join(where or self.src, f"{name}.csv")
            if not os.path.exists(p):
                self._csv[key] = None
            else:
                try:
                    self._csv[key] = pd.read_csv(p, keep_default_na=True)
                except pd.errors.EmptyDataError:
                    self._csv[key] = pd.DataFrame()
        df = self._csv[key]
        rel = os.path.relpath(os.path.join(where or self.src, f"{name}.csv"), OUT)
        if df is None:
            raise Skip(f"{rel} not found")
        if df.empty:
            raise Skip(f"{rel} has no rows")
        miss = [c for c in cols if c not in df.columns]
        if miss:
            self.missing.append((rel, miss))
            raise Skip(f"{rel} lacks columns {', '.join(miss)}")
        return df

    def maybe(self, name, cols=(), where=None):
        try:
            return self.csv(name, cols, where)
        except Skip as e:
            self.note(str(e))
            return None

    def note(self, s):
        if s not in self.notes_list:
            self.notes_list.append(s)

    # -- outputs
    def write(self, rel, text):
        p = os.path.join(self.dst, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as f:
            f.write(text)
        self.made.append(rel)

    def table(self, name, caption, label, body, size="footnotesize", sep=None):
        """One float: `body` is a list of tabular blocks (spec string, header rows, body rows)."""
        out = [GENERATOR.format(scope=self.scope), r"\begin{table}[tbp]", r"  \centering", rf"  \{size}"]
        if sep:
            out.append(rf"  \setlength{{\tabcolsep}}{{{sep}}}")
        out += [rf"  \caption{{{caption}}}", rf"  \label{{{label}}}"]
        for i, (spec, head, rows) in enumerate(body):
            if i:
                out.append(r"  \\[6pt]")
            out += [rf"  \begin{{tabular}}{{{spec}}}", r"    \toprule"]
            out += ["    " + h for h in head] + [r"    \midrule"]
            out += ["    " + r for r in rows] + [r"    \bottomrule", r"  \end{tabular}"]
        out.append(r"\end{table}")
        self.write(f"tables/{name}.tex", "\n".join(out) + "\n")
        self.changes[name] = label

    def table_raw(self, name, text):
        """A float rendered elsewhere (the validity table), under the generator line."""
        self.write(f"tables/{name}.tex", GENERATOR.format(scope=self.scope) + "\n" + text)
        self.changes[name] = re.search(r"\\label\{([^}]+)\}", text).group(1)

    def figure(self, name, fig, caption, label, width=None):
        os.makedirs(os.path.join(self.dst, "figures"), exist_ok=True)
        fig.savefig(os.path.join(self.dst, "figures", f"{name}.pdf"), bbox_inches="tight",
                    metadata={"CreationDate": None, "ModDate": None, "Producer": None, "Creator": None})
        plt.close(fig)
        self.made.append(f"figures/{name}.pdf")
        w = f"[{width}]" if width else ""
        self.write(f"figures/{name}.tex", "\n".join([
            GENERATOR.format(scope=self.scope), r"\begin{figure}[tbp]", r"  \centering",
            rf"  \thesisfig{w}{{{name}.pdf}}", rf"  \caption{{{caption}}}", rf"  \label{{{label}}}",
            r"\end{figure}"]) + "\n")
        self.changes[name] = label

    def d(self, section, text):
        self.digest[section].append(text)


