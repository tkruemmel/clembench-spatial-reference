def generic_table(pk, name, df, slot, what):
    keys = [c for c in df.columns if df[c].dtype == object][:4]
    nums = [c for c in df.columns if c not in keys and pd.api.types.is_numeric_dtype(df[c])][:max(1, 8 - len(keys))]
    cols = keys + nums
    rows = []
    for _, r in df.head(40).iterrows():
        rows.append(" & ".join(E(r[c]) if c in keys else T(f"{float(r[c]):.3g}" if ok(r[c]) else "---") for c in cols) + r" \\")
    head = [" & ".join(E(c.replace("_", " ")) for c in cols) + r" \\"]
    trunc = f" The first 40 of {len(df)} rows are shown." if len(df) > 40 else ""
    dropped = [c for c in df.columns if c not in cols]
    cap = (rf"{E(name.replace("_", " "))}, {what}, {pk.arm}. The columns are as the analysis writes them.{trunc} "
           + (rf"Columns left out are {E(', '.join(dropped))}. " if dropped else "") + r"Exploratory; compliance and uptake rates are "
           r"associational, and only the referent swap is causal, for one step. " + pk.status)
    pk.table(name, cap, f"tab:msg-{name.replace('_', '-')}", [("l" * len(keys) + "r" * len(nums), head, rows)],
             size="scriptsize", sep="3pt")
    pk.d(f"ext {slot}", f"- {name}: {len(df)} rows, columns {', '.join(df.columns)} (rendered generically; see the float).")


