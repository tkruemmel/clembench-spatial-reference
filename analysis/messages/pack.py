def cell_txt(r, scale=100, d=1, base=None):
    """(value, n) of one cell row: est [lo, hi], with a chance or baseline value."""
    v = ci(r["est"], r.get("lo"), r.get("hi"), scale, d)
    if base is not None and ok(r.get(base)):
        v += f" ({fnum(r[base], d, scale)})"
    return v, r.get("n")


def tex_cell(v, n, always=False):
    s = T(v)
    if ok(n) and (always or int(float(n)) != FULL_CELL):
        s += rf"\textsubscript{{{int(float(n))}}}"
    return s


def long_blocks(df, blocks, contrasts=None, md_out=None):
    """Long-format cell tables, suites as columns: per block a header row, then
    one row per model and protocol. blocks: [(label, filter dict, scale, decimals,
    baseline column, contrast measure or None)]. Returns tabular rows; md_out
    collects (label, markdown rows)."""
    rows = []
    for label, filt, scale, dec, base, cmeasure in blocks:
        sub = df
        for k, v in filt.items():
            sub = sub[sub[k] == v]
        if sub.empty:
            continue
        if rows:
            rows.append(r"\midrule")
        rows.append(rf"\multicolumn{{5}}{{l}}{{\emph{{{label}}}}} \\")
        mrows = []
        for m, mname in MODELS:
            first = True
            for p in PROTOS:
                s = sub[(sub.model == m) & (sub.proto == p)]
                if s.empty:
                    continue
                vals = []
                for su in SUITES:
                    c = s[s.suite == su]
                    vals.append(cell_txt(c.iloc[0], scale, dec, base) if len(c) else ("---", None))
                rows.append(rf"\quad {mname if first else ''} & {sc(p)} & " + " & ".join(tex_cell(*v) for v in vals) + r" \\")
                mrows.append([mname, p] + [f"{v} (n {int(float(n))})" if ok(n) else v for v, n in vals])
                first = False
            if contrasts is not None and cmeasure is not None:
                c = contrasts[(contrasts.measure == cmeasure) & (contrasts.model == m)]
                if len(c):
                    vals = []
                    for su in SUITES:
                        x = c[c.suite == su]
                        if len(x):
                            x = x.iloc[0]
                            vals.append(f"{sg(x['mean'], dec, scale)} (p {pv(x['p'])})")
                        else:
                            vals.append("---")
                    rows.append(r"\quad & \emph{free.$-$hyb.} & " +
                                " & ".join(T(v).replace("(p ", "($p$ ") for v in vals) + r" \\")
                    mrows.append([mname, "freeform - hybrid"] + vals)
        if md_out is not None:
            md_out.append((label, mrows, dict(filt, scale=scale, dec=dec, contrast=cmeasure is not None and contrasts is not None),
                           _ranges(sub, scale, dec)))
    return rows


def _ranges(sub, scale, dec):
    """Range of the cell estimates per tier, for the headline line."""
    out = []
    for tier, models in (("strong", ("qwen38", "dsv41")), ("Nemotron", ("nemotron",))):
        x = sub[sub.model.isin(models) & (pd.to_numeric(sub["n"], errors="coerce") >= 10)]["est"].dropna()
        if len(x):
            out.append(f"{tier} {fnum(x.min(), dec, scale)}-{fnum(x.max(), dec, scale)}")
    return ", ".join(out)


