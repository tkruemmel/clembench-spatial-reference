def pcols(*widths, last=""):
    """A tabular spec of ragged-right p columns, widths as fractions of the line."""
    return "@{}" + "".join(rf">{{\raggedright\arraybackslash}}p{{{w}\linewidth}}" for w in widths) + last + "@{}"


def _float(caption, label, spec, head, rows, size="footnotesize"):
    return ([r"\begin{table}[tbp]", r"  \centering", rf"  \{size}", rf"  \caption{{{caption}}}", rf"  \label{{{label}}}",
             rf"  \begin{{tabular}}{{{spec}}}", r"    \toprule"] + ["    " + h for h in head] + [r"    \midrule"] +
            ["    " + r for r in rows] + [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""])


