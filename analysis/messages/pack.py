def md_long(pk, section, blocks_md, unit, name=None):
    heads = []
    for label, mrows, f, rng in blocks_md:
        key = f.get("measure") or f.get("value") or f.get("channel") or ("rate" if "region" in f else None)
        test = (" Rows `freeform - hybrid`: board-paired studentized sign-flip contrast on the prose part, exploratory."
                if f.get("contrast") else "")
        cl = claim(CLAIM_OF[key]) if key in CLAIM_OF else ""
        pk.d(section, f"**{plain(label)}** ({unit}). Range of the cell estimates with at least 10 episodes: {rng or 'none'}.{test}"
                      + (f" Claim it may support: {cl}." if cl else "") +
             "\n\n| model | protocol | dyad | 3p | 6p |\n|---|---|---|---|---|\n" +
             "\n".join("| " + " | ".join(md(x) for x in r) + " |" for r in mrows) + "\n")
        heads.append(f"{plain(label)}: {rng}")
    if name:
        pk.key[name] = "; ".join(heads)


def claim(measure_prefix):
    for r in tables.validity_rows():
        if r["measure"].startswith(measure_prefix):
            return r["claims"]
    return ""


