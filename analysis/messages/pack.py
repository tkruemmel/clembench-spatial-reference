def _vocab_label(name, meta):
    side = lambda s: sc(s) if s in PROTOS else E(s)
    m = re.search(r"_(dyad|3p|6p)_", name + "_")
    win = {"first": ", first messages", "prefatal": ", before the first fatal decision"}.get(meta.get("window"), "")
    reg = {"prose": "prose", "plan+request": "slots"}.get(meta.get("regions"), E(meta.get("regions", "")))
    if name.endswith("_freeform") and meta["side_a"] not in PROTOS:
        reg = sc("freeform") + " " + reg
    return f"{side(meta['side_a'])} vs {side(meta['side_b'])}, {reg}{', ' + m.group(1) if m and 'success' in name else ''}{win}"


