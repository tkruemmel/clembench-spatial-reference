def _cellrows(df, keys=("model", "suite", "proto")):
    """Rows of df in model, suite, protocol order."""
    order = {m: i for i, (m, _) in enumerate(MODELS)}
    df = df.assign(_m=df.model.map(order), _s=df.suite.map({s: i for i, s in enumerate(SUITES)}),
                   _p=df.proto.map({p: i for i, p in enumerate(PROTOS)}))
    return df.dropna(subset=["_m", "_s", "_p"]).sort_values(["_m", "_s", "_p"])


