def wide_cells(pk, df, metrics, name, label, caption, section):
    """Model x suite x protocol rows, one column per metric (point estimates);
    the intervals go to the digest and their largest half-width to the caption."""
    df = df[df.level == "all"] if "level" in df.columns else df
    metrics = [(m, h) for m, h in metrics if m in set(df.metric)]
    if not metrics:
        raise Skip(f"{name}: none of its metrics in rp_cells.csv")
    rows, prev, half = [], (None, None), {"strong": 0.0, "weak": 0.0}
    for _, k in _cellrows(df.drop_duplicates(["model", "suite", "proto"])).iterrows():
        m, su, p = k["model"], k["suite"], k["proto"]
        c = df[(df.model == m) & (df.suite == su) & (df.proto == p)].set_index("metric")
        vals, dig = [], []
        for met, h in metrics:
            if met not in c.index or not ok(c.loc[met, "est"]):
                vals.append("---")
                continue
            r, scale = c.loc[met], 1 if met in RP_RAW else 100
            vals.append(T(fnum(r["est"], 1, scale)))
            if scale == 100 and ok(r["lo"]) and ok(r["hi"]):
                t = "weak" if m == "nemotron" else "strong"
                half[t] = max(half[t], abs(float(r["est"]) - float(r["lo"])), abs(float(r["hi"]) - float(r["est"])))
            dig.append(f"{met} {ci(r['est'], r['lo'], r['hi'], scale)} (n {int(r['n'])})")
        lm, ls = _lead(prev, m, su)
        prev = (m, su, p)
        rows.append(rf"{lm} & {ls} & {sc(p)} & " + " & ".join(vals) + r" \\")
        pk.d(section, f"- {MNAME.get(m, m)} {su} {p}: " + "; ".join(dig) + ".")
    hw = " and ".join(f"$\\pm${T(fnum(v, 1, 100))} points for the {'strong tier' if t == 'strong' else 'weak tier'}"
                      for t, v in half.items() if v)
    cap = caption + (rf" The 95\,\% level-stratified bootstrap intervals lie within {hw} and are in the digest." if hw else "")
    pk.table(name, cap + " " + pk.status, label,
             [("lll" + "r" * len(metrics), [r"Model & Suite & Protocol & " + " & ".join(h for _, h in metrics) + r" \\"], rows)],
             size="scriptsize", sep="2pt")


