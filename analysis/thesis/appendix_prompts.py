#!/usr/bin/env python3
"""Appendix A: the prompts of the final arm, and one turn as a player sees it.

    python3 analysis/thesis/appendix_prompts.py > thesis/appendix_prompts.tex

The templates are read from matrixgame/resources as they are, and the turn
block is rendered by matrixgame/master.py on a real dyad instance, so rerun
this after any prompt or master change rather than hand-editing the .tex.
"""

import importlib.util
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
GAME = REPO / "matrixgame"
PROMPTS = GAME / "resources" / "initial_prompts" / "en"
PROTOCOLS = ("none", "structured", "freeform", "hybrid")

_ESCAPE = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$", "&": r"\&", "#": r"\#",
           "%": r"\%", "_": r"\_", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
           "`": r"\textasciigrave{}", " ": r"\ ", "-": "-{}"}  # -{} stops -- and --- becoming dashes


def typed(text):
    """Text exactly as sent, in typewriter. Every space is kept (the boards
    depend on it) and long lines wrap at spaces; the leading \\mbox{} keeps
    indentation and stops a line opening with [ or * reading as an argument."""
    lines = [r"\mbox{}" + "".join(_ESCAPE.get(c, c) for c in line) for line in text.rstrip("\n").split("\n")]
    return "\\begin{flushleft}\\ttfamily\\footnotesize\n" + "\\\\\n".join(lines) + "\n\\end{flushleft}\n"


def template(game, variant=None):
    name = "player_prompt" if variant is None else f"player_prompt_{variant}"
    return (PROMPTS / game / f"{name}.template").read_text(encoding="utf-8")


def turn_block():
    """Player Green's context on turn 11 of a scripted freeform episode on S3 board 1."""
    sys.path.insert(0, str(GAME))  # the master imports its helpers as utils.*
    spec = importlib.util.spec_from_file_location("matrixgame_master", GAME / "master.py")
    M = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(M)
    from clemcore.clemgame.registry import GameSpec

    exp = next(e for e in json.loads((GAME / "in/instances_dyad.json").read_text())["experiments"]
               if e["name"] == "S3_freeform")
    inst = exp["game_instances"][0]

    class Model:
        name = "scripted"

        def set_gen_arg(self, *_):
            pass

    m = M.TeamMatrixGameMaster(GameSpec(game_name="matrixgame_dyad", game_path=str(GAME), players=2), exp,
                               [Model(), Model()])
    m._on_setup(**inst)
    a, b = m.get_players()
    cell = lambda rc: f"(R{rc[0] + 1},C{rc[1] + 1})"
    back = {"up": "down", "down": "up", "left": "right", "right": "left"}

    def closer(p):
        """The first legal move that brings one of p's objects nearer its target."""
        dist = lambda o, r, c: abs(r - m.board.target_positions[o][0]) + abs(c - m.board.target_positions[o][1])
        # Ties by letter: the objects come as a set, whose order changes with the hash seed.
        for o in sorted(m._objects_for(p), key=lambda o: (-dist(o, *m.board.object_positions[o]), o)):
            r, c = m.board.object_positions[o]
            for d, (dr, dc) in M.DIRECTIONS.items():
                if dist(o, r + dr, c + dc) < dist(o, r, c) and \
                        m.board.validate_move(o, d, allowed_objects=m._objects_for(p)) is None:
                    return o, d
        raise RuntimeError("no closer move")

    def play(p, o, d, msg):
        response = f"message: {msg}\nmove: {o} {d}"
        assert m._validate_player_response(p, response), response
        m._on_valid_player_response(p, m._parse_response(p, response))

    for t in range(6):
        p = a if t % 2 == 0 else b
        o, d = closer(p)
        goal = cell(m.board.target_positions[o])
        play(p, o, d, f"I'm moving {o} {d} toward its goal at {goal}. Tell me if it gets in your way." if p is a
             else f"Got it. I'm moving my {o} {d}; its target is {goal}. Shout if I block you.")
    oa, da = closer(a)
    play(a, oa, da, f"Moving {oa} {da} toward its goal at {cell(m.board.target_positions[oa])}.")
    ob, db = closer(b)
    play(b, ob, db, f"Thanks. Moving {ob} {db}.")
    play(a, oa, back[da], f"On second thought, {oa} can wait. Moving it back {back[da]}.")
    play(b, ob, back[db], f"OK, I'll step {ob} back {back[db]} too so you can sort that out first.")
    return inst["game_id"], m.get_context_for(a)["content"]


def main():
    game_id, block = turn_block()
    out = [r"""% =====================================================================
%  Appendix A.  GENERATED by analysis/thesis/appendix_prompts.py from
%  matrixgame/resources and matrixgame/master.py -- re-run it rather than
%  hand-editing, or the prompts drift from what the games send.
% =====================================================================
\chapter{Prompts}
\label{app:prompts}

This appendix reproduces the nine prompt templates of the three games, and one turn as a player receives it. Every call to a model sends a single message. It opens with the template of the player's game and condition, which stays fixed for the episode, and continues, after a blank line, with the block for the current turn (Section~\ref{app:prompts-turn}). Four placeholders in the templates are filled in at the start of the episode. \texttt{\$GRID\_SIZE\$} becomes 8, \texttt{\$YOUR\_OBJECTS\$} the player's own object letters separated by commas (for example \texttt{A, D}), \texttt{\$YOUR\_ROLE\$} the player's name (\texttt{Player Blue}), and \texttt{\$N\_OTHER\_PLAYERS\$} the number of teammates, 2 or 5. Everything else is printed as the models receive it, line breaks and spacing included.
""",
           r"\section{Solo}" + "\n", typed(template("solo"))]
    out.append(r"\section{Dyad}" + "\n")
    for protocol in PROTOCOLS:
        out += [rf"\paragraph{{\textsc{{{protocol}}}}}" + "\n", typed(template("dyad", protocol))]
    out.append(r"\section{Three and six players}" + "\n"
               "The three- and six-player games share these four prompts.\n")
    for protocol in PROTOCOLS:
        out += [rf"\paragraph{{\textsc{{{protocol}}}}}" + "\n", typed(template("nplayer", protocol))]
    out.append(rf"""\section{{One turn}}
\label{{app:prompts-turn}}

The block below is what Player~Green receives after its prompt on turn 11 of a dyad episode under \textsc{{freeform}} on S3 board {game_id}. The moves and messages were scripted for this illustration and are not model output; the block is rendered by the game master exactly as in play. On turns 9 and 10 both players undo their previous move, which the move board shows and the current board alone would not. Under \textsc{{none}} there is no message board, and in solo the move board is the only one. A teammate's \texttt{{done}} declaration appears only on the message board, as a line such as \texttt{{Player Orange declared done}} in place of its message, and leaves the board with its round.
""")
    out.append(typed(block))
    print("\n".join(out))


if __name__ == "__main__":
    main()
